#!/usr/bin/env python3
"""Turn vendored shader sources into a C header holding them as one string.

The Vulkan backend compiles its own full-screen passes from GLSL at run time
(rsx_glsl_to_spirv). Third-party shader libraries (third_party/smaa/SMAA.hlsl,
third_party/fxaa/FXAA3_11.h, third_party/ffx_cas/ffx_{a,cas}.h) are kept
byte-for-byte as their authors ship them; this script makes the C string the
backend prepends to its own wrapper code. Comments and blank lines are dropped
(the strings stay small and ASCII); the library's licence block -- the first
comment of each input -- is copied into the header as a C comment, so the
notice travels with every copy of the code.

  python tools/gen_glsl_header.py --name kSmaaGLSL \
      --out third_party/smaa/smaa_glsl.h third_party/smaa/SMAA.hlsl
"""
import argparse
import os
import re
import sys


def first_comment(text, stop=None):
    """The leading comment block (// lines or one /* */), as plain lines, up to
    (not including) the first line matching `stop`."""
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and lines[i].lstrip().startswith("/*"):
        while i < len(lines):
            out.append(lines[i])
            if "*/" in lines[i]:
                break
            i += 1
    else:
        while i < len(lines) and lines[i].lstrip().startswith("//"):
            if stop and re.search(stop, lines[i]):
                break
            out.append(lines[i])
            i += 1
    return [l.replace("*/", "* /") for l in out]


def strip_comments(text):
    """Remove /* */ and // comments (shader code has no string literals)."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            if j < 0:
                raise SystemExit("unterminated /* comment")
            # keep the newlines so line structure (and #directives) survive
            out.append("\n" * text.count("\n", i, j))
            out.append(" ")
            i = j + 2
        elif c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            i = n if j < 0 else j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def c_lines(code):
    for line in code.splitlines():
        line = line.rstrip()
        if not line.strip():
            continue
        if any(ord(ch) > 126 or (ord(ch) < 32 and ch != "\t") for ch in line):
            raise SystemExit("non-ASCII character left in code: %r" % line)
        yield '"' + line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "    ") + '\\n"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True, help="C identifier of the string")
    ap.add_argument("--out", required=True)
    ap.add_argument("--notice-stop", default=None,
                    help="regex: the copied licence block ends before the first line matching it")
    ap.add_argument("inputs", nargs="+")
    a = ap.parse_args()
    body, notices = [], []
    for path in a.inputs:
        with open(path, "rb") as f:
            text = f.read().decode("latin-1").replace("\r\n", "\n").replace("\r", "\n")
        notices.append((os.path.basename(path), first_comment(text, a.notice_stop)))
        body.extend(c_lines(strip_comments(text)))
    guard = "PS3RECOMP_" + a.name.upper() + "_H"
    with open(a.out, "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_glsl_header.py from %s -- do not edit.\n"
                % ", ".join(os.path.basename(p) for p in a.inputs))
        stop = " --notice-stop \"%s\"" % a.notice_stop if a.notice_stop else ""
        f.write(" * Regenerate with:\n *   python tools/gen_glsl_header.py --name %s%s --out %s %s\n"
                % (a.name, stop, a.out.replace("\\", "/"), " ".join(p.replace("\\", "/") for p in a.inputs)))
        f.write(" * Comments are stripped from the code; each input's licence block follows. */\n")
        for name, lines in notices:
            f.write("/* ---- %s ----\n" % name)
            for l in lines:
                f.write(" * " + l.rstrip() + "\n")
            f.write(" */\n")
        f.write("#ifndef %s\n#define %s\n" % (guard, guard))
        f.write("static const char %s[] =\n" % a.name)
        for l in body:
            f.write("    " + l + "\n")
        f.write("    ;\n#endif\n")
    print("%s: %d lines" % (a.out, len(body)))


if __name__ == "__main__":
    sys.exit(main())
