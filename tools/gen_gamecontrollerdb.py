#!/usr/bin/env python3
"""Generate libs/input/gamecontrollerdb_win.h from the vendored SDL_GameControllerDB.

    python tools/gen_gamecontrollerdb.py [--db third_party/SDL_GameControllerDB/gamecontrollerdb.txt]

Only the "platform:Windows" lines are kept (SDL ignores the other platforms'
lines anyway), one C string per mapping, so cellPad.c can hand each to
SDL_GameControllerAddMapping at start-up without a file next to the exe.
"""
import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=os.path.join(ROOT, "third_party", "SDL_GameControllerDB", "gamecontrollerdb.txt"))
    ap.add_argument("--out", default=os.path.join(ROOT, "libs", "input", "gamecontrollerdb_win.h"))
    a = ap.parse_args()
    raw = open(a.db, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    lines = []
    for ln in raw.decode("utf-8", "replace").splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#") or "platform:Windows," not in ln:
            continue
        lines.append(ln)
    out = []
    out.append("/* GENERATED by tools/gen_gamecontrollerdb.py -- do not edit.")
    out.append(" *")
    out.append(" * The Windows mappings of SDL_GameControllerDB (third_party/SDL_GameControllerDB,")
    out.append(" * zlib license, see its LICENSE and README.txt), one string per controller,")
    out.append(" * for SDL_GameControllerAddMapping (libs/input/cellPad.c).")
    out.append(" * source sha256 %s, %d mappings" % (sha, len(lines)))
    out.append(" */")
    out.append("#ifndef PS3RECOMP_GAMECONTROLLERDB_WIN_H")
    out.append("#define PS3RECOMP_GAMECONTROLLERDB_WIN_H")
    out.append("")
    out.append("static const char* const kPadDbWindows[] = {")
    for ln in lines:
        out.append("    " + c_string(ln) + ",")
    out.append("};")
    out.append("#define PAD_DB_WINDOWS_COUNT %d" % len(lines))
    out.append("")
    out.append("#endif")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%s: %d Windows mappings (%d bytes)" % (a.out, len(lines), os.path.getsize(a.out)))


if __name__ == "__main__":
    main()
